public class Pont {

    private double x;
    private double y;

    public Pont(){
        this.x = 8.5;
        this.y = 9.3;
    }

    public double getY() {
        return y;
    }

    public void setY(double y) {
        this.y = y;
    }

    public double getX() {
        return x;
    }

    public void setX(double x) {
        this.x = x;
    }
}
